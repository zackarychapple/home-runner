//! Installing requirements: a derived image with them baked in.
//!
//! Workers are throwaway, so anything installed in one is gone with it. The app therefore builds a
//! second image from the pool's own, running the install script as root once, and points the pool
//! at it. Jobs get an immutable copy: a job cannot change the next job's tools or browsers.
//!
//! Only what the operator wrote in their own config runs here: apt packages, the built-in
//! Playwright recipe, and `install` scripts on `command` requirements. A repository's workflow
//! never supplies a script.

use base64::Engine;

use super::probe::sh_quote;
use super::{ProfileConfig, Requirement};

pub const LABEL_FINGERPRINT: &str = "dev.home-runner.fingerprint";
pub const LABEL_BASE_ID: &str = "dev.home-runner.base-id";

/// The root-run script that makes a base image satisfy the profile. Safe to run again: apt, npm and
/// Playwright all skip what is already there.
pub fn script(profile: &ProfileConfig) -> String {
    let mut out = String::from(
        r#"set -eu
export DEBIAN_FRONTEND=noninteractive
hr_apt_updated=0
hr_apt() {
  if [ "$hr_apt_updated" = 0 ]; then apt-get update; hr_apt_updated=1; fi
  apt-get install -y --no-install-recommends "$@"
}
"#,
    );
    let mut apt_used = false;
    for req in &profile.requirements {
        match req {
            Requirement::Command(c) => {
                if let Some(script) = &c.install {
                    out.push_str(&format!(
                        "echo {}\n(\n{}\n)\n",
                        sh_quote(&format!("home-runner: installing {}", c.name)),
                        script.trim_end()
                    ));
                }
            }
            Requirement::Apt(a) => {
                apt_used = true;
                out.push_str(&format!(
                    "echo {}\nhr_apt {}\n",
                    sh_quote(&format!("home-runner: apt {}", a.packages.join(" "))),
                    a.packages
                        .iter()
                        .map(|p| sh_quote(p))
                        .collect::<Vec<_>>()
                        .join(" ")
                ));
            }
            // The daemon comes from the image (dockerd) and the pool (docker_in_job); there is
            // nothing for a build to add that wouldn't be a guess.
            Requirement::Docker(_) => {}
            Requirement::Playwright(p) => {
                apt_used = true;
                let root = p.root.trim_end_matches('/');
                out.push_str(&format!(
                    r#"echo 'home-runner: installing Playwright browsers'
command -v node >/dev/null 2>&1 && command -v npm >/dev/null 2>&1 || {{
  echo 'home-runner: Playwright needs node and npm in the image; list them as requirements before it' >&2
  exit 1
}}
case "$(uname -s)" in Linux) o=linux ;; Darwin) o=macos ;; *) o=$(uname -s) ;; esac
case "$(uname -m)" in aarch64|arm64) a=arm64 ;; x86_64|amd64) a=x64 ;; *) a=$(uname -m) ;; esac
root={root}
bp="$root/$o-$a/browsers"
mkdir -p "$root/runtime" "$bp"
"#,
                    root = sh_quote(root)
                ));
                for v in &p.versions {
                    let browsers = p.browsers.join(" ");
                    out.push_str(&format!(
                        r#"if [ ! -f "$root/runtime/{v}/node_modules/playwright-core/package.json" ]; then
  mkdir -p "$root/runtime/{v}"
  npm install --prefix "$root/runtime/{v}" --no-audit --no-fund playwright-core@{v}
fi
PLAYWRIGHT_BROWSERS_PATH="$bp" node "$root/runtime/{v}/node_modules/playwright-core/cli.js" install --with-deps {browsers}
"#
                    ));
                }
                // Readable and runnable by everyone, writable by no one but root.
                out.push_str("chmod -R a+rX,go-w \"$root\"\n");
            }
        }
    }
    if apt_used {
        out.push_str("rm -rf /var/lib/apt/lists/*\n");
    }
    out
}

/// The Dockerfile for the derived image. It ends back on the base image's own user, because the
/// probe (and the runner) must not run as root.
pub fn dockerfile(
    base: &str,
    base_user: Option<&str>,
    base_id: Option<&str>,
    profile: &ProfileConfig,
    fingerprint: &str,
) -> String {
    let encoded = base64::engine::general_purpose::STANDARD.encode(script(profile));
    let mut out = format!(
        "# Generated by home-runner for profile {name} (version {version}). Do not edit.\n\
         FROM {base}\n\
         USER root\n\
         RUN echo '{encoded}' | base64 -d > /tmp/hr-install.sh && sh /tmp/hr-install.sh && rm -f /tmp/hr-install.sh\n\
         LABEL {LABEL_FINGERPRINT}=\"{fingerprint}\" dev.home-runner.profile=\"{name}\" \
         dev.home-runner.profile-version=\"{version}\"",
        name = profile.name,
        version = profile.version,
    );
    if let Some(id) = base_id {
        out.push_str(&format!(" {LABEL_BASE_ID}=\"{id}\""));
    }
    out.push('\n');
    if let Some(user) = base_user.filter(|u| !u.is_empty()) {
        out.push_str(&format!("USER {user}\n"));
    }
    out
}

#[cfg(test)]
mod tests {
    use super::super::tests::{WITH_TAP, profile};
    use super::*;

    #[test]
    fn the_install_script_covers_each_requirement_in_order() {
        let script = script(&profile(WITH_TAP));
        let actionlint = script.find("installing actionlint").unwrap();
        let apt = script.find("hr_apt 'libasound2-dev' 'pkg-config'").unwrap();
        let playwright = script.find("installing Playwright browsers").unwrap();
        assert!(actionlint < apt && apt < playwright);
        // The operator's own install script is what runs, and only inside its own subshell.
        assert!(script.contains("(\ncurl -fsSL https://example.test/actionlint.tgz"));
        // One runtime and one browser install per pinned version, side by side.
        assert!(script.contains("npm install --prefix \"$root/runtime/1.56.1\""));
        assert!(script.contains("npm install --prefix \"$root/runtime/1.49.0\""));
        assert_eq!(
            script
                .matches("cli.js\" install --with-deps chromium")
                .count(),
            2
        );
        // Nothing but root can change it afterwards.
        assert!(script.contains("chmod -R a+rX,go-w \"$root\""));
        // dockerd is not guessed at.
        assert!(!script.contains("docker-ce"));
        assert!(script.contains("rm -rf /var/lib/apt/lists/*"));
    }

    #[test]
    fn a_profile_without_installable_requirements_makes_a_script_that_does_nothing() {
        let p = profile("name = \"p\"\n[[require]]\nkind = \"command\"\nname = \"git\"");
        let s = script(&p);
        assert!(!s.contains("apt-get install -y --no-install-recommends \"$@\"\n  hr_apt '"));
        assert!(!s.contains("rm -rf /var/lib/apt"));
    }

    #[cfg(unix)]
    #[test]
    fn install_scripts_are_valid_shell() {
        let status = std::process::Command::new("sh")
            .args(["-n", "-c", &script(&profile(WITH_TAP))])
            .status()
            .unwrap();
        assert!(status.success());
    }

    #[test]
    fn the_dockerfile_restores_the_runner_user_and_records_what_it_was_built_from() {
        let p = profile(WITH_TAP);
        let text = dockerfile("base:1", Some("runner"), Some("sha256:abc"), &p, "fp123");
        let lines: Vec<_> = text.lines().collect();
        assert_eq!(lines[1], "FROM base:1");
        assert_eq!(lines[2], "USER root");
        assert!(lines[3].starts_with("RUN echo '"));
        assert!(text.contains("dev.home-runner.fingerprint=\"fp123\""));
        assert!(text.contains("dev.home-runner.base-id=\"sha256:abc\""));
        assert_eq!(*lines.last().unwrap(), "USER runner");
        // The script round-trips through base64, so no quoting in it can break the Dockerfile.
        let encoded = lines[3].split('\'').nth(1).unwrap();
        let decoded = base64::engine::general_purpose::STANDARD
            .decode(encoded)
            .unwrap();
        assert_eq!(String::from_utf8(decoded).unwrap(), script(&p));
        // A root-default base image stays that way rather than gaining an empty USER line.
        let text = dockerfile("base:1", None, None, &p, "fp");
        assert!(!text.contains("base-id") && text.lines().last().unwrap().starts_with("LABEL"));
    }
}
